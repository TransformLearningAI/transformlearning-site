import { Resend } from 'resend'
import { checkActionSig, makeAccessKey } from '@/lib/access-token'

const resend = new Resend(process.env.RESEND_API_KEY)

const htmlPage = (title, icon, heading, detail) => `
  <html>
    <head><title>${title}</title></head>
    <body style="font-family: system-ui; max-width: 500px; margin: 80px auto; text-align: center; color: #1a1a2e;">
      <div style="font-size: 48px; margin-bottom: 16px;">${icon}</div>
      <h1 style="font-size: 24px; margin-bottom: 8px;">${heading}</h1>
      <p style="color: #666; font-size: 14px;">${detail}</p>
      <p style="color: #999; font-size: 12px; margin-top: 24px;">You can close this tab.</p>
    </body>
  </html>
`

// Only links generated by /api/request-access carry a valid signature.
// Anyone else who calls this endpoint is refused and no email is sent.
export async function GET(request) {
  const { searchParams } = new URL(request.url)
  const email = (searchParams.get('email') || '').trim()
  const name = (searchParams.get('name') || 'there').slice(0, 100)
  const action = searchParams.get('action')
  const sig = searchParams.get('sig')

  if (!email || !action) {
    return new Response('Missing parameters.', { status: 400, headers: { 'Content-Type': 'text/html' } })
  }
  if (!checkActionSig(email, action, sig)) {
    return new Response('Invalid or missing signature.', { status: 403, headers: { 'Content-Type': 'text/plain' } })
  }

  try {
    if (action === 'approve') {
      // The key is minted here on the server. The client never supplies it.
      const key = makeAccessKey(email)
      const methodologyLink = `https://transformlearning.ai/methodology?access=${key}`
      const investorLink = `https://transformlearning.ai/investors?access=${key}`

      await resend.emails.send({
        from: 'Transform Learning <noreply@transformlearning.ai>',
        to: email,
        subject: 'Your access has been approved - Transform Learning',
        text: [
          `Hi ${name},`,
          '',
          'Your access request has been approved. Here are your personal access links:',
          '',
          'Proficiency Scoring Methodology:',
          methodologyLink,
          '',
          'Investor Overview / Go-to-Market Strategy:',
          investorLink,
          '',
          'These links are personal to you. Please do not share them.',
          '',
          'If you have questions about what you read, feel free to reply to this email.',
          '',
          'Best,',
          'Jeff Ritter, PhD',
          'Founder, Transform Learning',
          'transformlearning.ai',
        ].join('\n'),
      })

      return new Response(
        htmlPage('Access Approved', '&#x2705;', 'Access approved.',
          `An email with access links has been sent to <strong>${email}</strong>.`),
        { status: 200, headers: { 'Content-Type': 'text/html' } }
      )
    }

    if (action === 'deny') {
      await resend.emails.send({
        from: 'Transform Learning <noreply@transformlearning.ai>',
        to: email,
        subject: 'Regarding your access request - Transform Learning',
        text: [
          `Hi ${name},`,
          '',
          'Thank you for your interest in Transform Learning. After reviewing your request, we are not able to provide access to our restricted materials at this time.',
          '',
          'You are welcome to explore our public demo at transformlearning.ai/demo and our blog at transformlearning.ai/blog.',
          '',
          'If your circumstances change or you have additional context to share, please feel free to submit a new request at transformlearning.ai/access.',
          '',
          'Best,',
          'The Transform Learning Team',
          'transformlearning.ai',
        ].join('\n'),
      })

      return new Response(
        htmlPage('Access Declined', '&#x1F6AB;', 'Access declined.',
          `A polite decline has been sent to <strong>${email}</strong>.`),
        { status: 200, headers: { 'Content-Type': 'text/html' } }
      )
    }

    return new Response('Invalid action.', { status: 400 })
  } catch (e) {
    console.error('Approve/deny error:', e)
    return new Response('Something went wrong. Try again.', { status: 500 })
  }
}
